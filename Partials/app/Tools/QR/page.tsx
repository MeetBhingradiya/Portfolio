    function TemplateConvertData(): string {
        function upiTransform() {
            // ? Only Add Required Properties whem other properties are not added
            let UPIURL = "upi://pay";

            if (State.TemplatesData?.upi?.pa) {
                UPIURL += `?${UPIPropeties.pa}=${State.TemplatesData?.upi?.pa}`;
            }
            if (State.TemplatesData?.upi?.pn) {
                UPIURL += `&${UPIPropeties.pn}=${State.TemplatesData?.upi?.pn}`;
            }
            if (State.TemplatesData?.upi?.mc) {
                UPIURL += `&${UPIPropeties.mc}=${State.TemplatesData?.upi?.mc}`;
            }
            if (State.TemplatesData?.upi?.tr) {
                UPIURL += `&${UPIPropeties.tr}=${State.TemplatesData?.upi?.tr}`;
            }
            if (State.TemplatesData?.upi?.url) {
                UPIURL += `&${UPIPropeties.url}=${State.TemplatesData?.upi?.url}`;
            }
            if (State.TemplatesData?.upi?.am) {
                UPIURL += `&${UPIPropeties.am}=${State.TemplatesData?.upi?.am}`;
            }
            if (State.TemplatesData?.upi?.cu) {
                UPIURL += `&${UPIPropeties.cu}=${State.TemplatesData?.upi?.cu}`;
            }
            if (State.TemplatesData?.upi?.tid) {
                UPIURL += `&${UPIPropeties.tid}=${State.TemplatesData?.upi?.tid}`;
            }
            if (State.TemplatesData?.upi?.tn) {
                UPIURL += `&${UPIPropeties.tn}=${State.TemplatesData?.upi?.tn}`;
            }
            if (State.TemplatesData?.upi?.gstBrkUp) {
                UPIURL += `&${UPIPropeties.gstBrkUp}=${State.TemplatesData?.upi?.gstBrkUp}`;
            }
            if (State.TemplatesData?.upi?.invoiceNo) {
                UPIURL += `&${UPIPropeties.invoiceNo}=${State.TemplatesData?.upi?.invoiceNo}`;
            }
            if (State.TemplatesData?.upi?.invoiceDate) {
                UPIURL += `&${UPIPropeties.invoiceDate}=${State.TemplatesData?.upi?.invoiceDate}`;
            }
            if (State.TemplatesData?.upi?.gstin) {
                UPIURL += `&${UPIPropeties.gstin}=${State.TemplatesData?.upi?.gstin}`;
            }

            return UPIURL;
        }

        switch (State.DataType) {
            case DataTypes.Text:
                return State.TemplatesData?.Text;
                break;
            case DataTypes.UPI:
                return upiTransform();
                break;
            case DataTypes.Wifi:
                return `WIFI:T:${State.TemplatesData?.wifi?.type};S:${State.TemplatesData?.wifi?.ssid};P:${State.TemplatesData?.wifi?.password};H:${State.TemplatesData?.wifi?.hidden ? "true" : "false"};`;
                break;
            case DataTypes.Bluetooth:
                return `B:${State.TemplatesData?.bluetooth?.name};${State.TemplatesData?.bluetooth?.address};`;
                break;
            case DataTypes.Contact:
                return `BEGIN:VCARD\nVERSION:3.0\nFN:${State.TemplatesData?.contact?.name}\nTEL:${State.TemplatesData?.contact?.phone}\nEMAIL:${State.TemplatesData?.contact?.email}\nADR:${State.TemplatesData?.contact?.address}\nORG:${State.TemplatesData?.contact?.org}\nTITLE:${State.TemplatesData?.contact?.title}\nURL:${State.TemplatesData?.contact?.url}\nEND:VCARD`;
                break;
            case DataTypes.Email:
                return `mailto:${State.TemplatesData?.email?.email}?subject=${State.TemplatesData?.email?.subject}&body=${State.TemplatesData?.email?.body}`;
                break;
            case DataTypes.Phone:
                return `tel:${State.TemplatesData?.Text}`;
                break;
        }
    }

